class AvailableLineageSources(BaseModel):
    """List the pseudocode files that are valid inputs for a lineage run."""
    user_id: str = Field("user2", description="The unique user id of a specific user (default: 'user2').")


class ReadLineageSources(BaseModel):
    """Read the chosen pseudocode files and lock the source-file scope for this run."""
    user_id: str = Field("user2", description="The unique user id of a specific user (default: 'user2').")
    job_files: List[str] = Field(..., description="List of pseudocode ETL job files to be used as lineage input.")


class LineageOptions(BaseModel):
    """Control the lineage abstraction, SQL visibility, lookup visibility, and optional LLM semantic enrichment."""
    diagram_mode: str = Field(
        "logical",
        description="Diagram abstraction level. Use 'logical' for a clean business-readable lineage or 'technical' for a more detailed graph."
    )
    include_sql_sources: bool = Field(
        False,
        description="Whether SQL source tables extracted from embedded SQL should be shown as visible lineage nodes."
    )
    collapse_intermediate_datasets: bool = Field(
        True,
        description="Whether anonymous transport datasets such as dataset_1 or dataset_17 should be collapsed into direct stage-to-stage relationships."
    )
    include_lookup_nodes: bool = Field(
        True,
        description="Whether lookup or hashed-file helper stages should remain visible in the final logical lineage."
    )
    llm_role_classification: bool = Field(
        False,
        description="Whether LLM-assisted stage-role classification should be used to refine SOURCE, LOOKUP, TRANSFORM, STORE, DECISION, or TARGET semantics before final normalization."
    )
    llm_business_labels: bool = Field(
        False,
        description="Whether LLM-assisted business-readable labels should be generated in addition to preserving original stage and table names."
    )
    llm_sql_grouping: bool = Field(
        False,
        description="Whether LLM-assisted SQL table grouping should be used to group staging, dimension, fact, or reference tables into clearer upstream source views."
    )


class DetectJobBoundaries(BaseModel):
    """Split selected pseudocode into independent jobs or pipelines and tag the parser family."""
    user_id: str = Field("user2", description="The unique user id of a specific user (default: 'user2').")
