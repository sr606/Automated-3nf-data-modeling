def _normalize_drawio_payload(payload):
    """
    Convert MCP/tool string payloads into raw XML or diagram bundles.
    """

    normalized = payload

    if isinstance(normalized, str):
        stripped = normalized.strip()

        if stripped.startswith("<mxfile") and '\\"' in stripped:
            normalized = (
                stripped
                .replace("\\r\\n", "\n")
                .replace("\\n", "\n")
                .replace('\\"', '"')
            )

    for _ in range(2):
        if not isinstance(normalized, str):
            break

        stripped = normalized.strip()

        if not stripped:
            return ""

        if stripped.startswith(("<mxfile", "{", "[")):
            break

        try:
            decoded = json.loads(stripped)
        except Exception:
            break

        if decoded == normalized:
            break

        normalized = decoded

    return normalized


