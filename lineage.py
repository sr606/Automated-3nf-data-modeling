@router.post(
    "/store_lineage_diagram",
    operation_id="store_lineage_diagram",
    summary="Store lineage diagram",
    description="Store generated draw.io XML lineage diagram."
)
async def store_lineage_diagram(p_body: StoreLineageDiagram):
    """
    Store lineage diagram.

    Saves generated draw.io XML diagram into lineage output directory.

    If no filename is supplied, this endpoint builds a deterministic filename
    from the selected source files and active lineage options. That behavior
    ensures rerunning the same lineage request overwrites the previous diagram
    instead of creating a new unrelated file.

    LLM usage guidance:
        - Call this after `generate_drawio_xml`.
        - Prefer omitting `diagram_filename` unless the user explicitly asked for a custom file name.
        - If multiple source files were selected, this tool stores one output file per source file by default.
        - Always report the stored filename or filenames back to the user in the final response.

    Returns:
        dict:
            diagram_filename (str): Stored lineage diagram filename.
    """

    try:
        normalized_payload = _normalize_drawio_payload(p_body.drawio_xml)
        parsed_payload = normalized_payload if isinstance(normalized_payload, (dict, list)) else None

        if isinstance(parsed_payload, dict) and isinstance(parsed_payload.get("diagrams"), list):
            stored_files = []
            lineage_options = methods.get_previous_state(p_body.user_id, "lineage_options") or {}
            output_dir = methods.get_lineage_output_dir(p_body.user_id, "diagrams")
            os.makedirs(output_dir, exist_ok=True)

            for diagram in parsed_payload["diagrams"]:
                source_file = diagram.get("source_file") or "lineage"
                xml = _normalize_drawio_payload(diagram.get("drawio_xml", ""))
                diagram_filename = methods.build_lineage_diagram_filename(
                    [source_file],
                    lineage_options,
                    extension=".drawio"
                )
                methods.store_lineage_xml(
                    xml,
                    output_dir,
                    diagram_filename
                )
                stored_files.append(diagram_filename)

            return {"diagram_filenames": stored_files}

        if not p_body.diagram_filename:
            source_files = methods.get_previous_state(p_body.user_id, "source_files") or []
            lineage_options = methods.get_previous_state(p_body.user_id, "lineage_options") or {}
            p_body.diagram_filename = methods.build_lineage_diagram_filename(
                source_files,
                lineage_options,
                extension=".drawio"
            )

        output_dir = methods.get_lineage_output_dir(p_body.user_id, "diagrams")

        os.makedirs(output_dir, exist_ok=True)

        methods.store_lineage_xml(
            normalized_payload if isinstance(normalized_payload, str) else json.dumps(normalized_payload),
            output_dir,
            p_body.diagram_filename
        )

        return {"diagram_filename": p_body.diagram_filename}

    except Exception as e:
        return {"error": str(e)}
