@router.post(
    "/detect_job_boundaries",
    operation_id="detect_job_boundaries",
    summary="Detect ETL pipeline boundaries",
    description="Identifies independent ETL pipelines within pseudocode files."
)
async def detect_job_boundaries(p_body: DetectJobBoundaries):
    """
    Detect job boundaries within pseudocode.

    ETL pseudocode files may contain multiple independent ETL pipelines.
    This tool detects boundaries separating each pipeline to ensure lineage
    graphs are constructed accurately.

    If a lineage source file is not explicitly provided,
    the tool automatically retrieves the most recent source file from lineage state.

    NOTE: Steps to follow:
        1. Generate lineage source using 'read_lineage_sources'.
        2. Call this endpoint to detect independent ETL pipelines.

    Returns:
        dict:
            Job_Boundaries_File (str): JSON file containing detected job boundaries.
    """

    try:

        execution_id = datetime.now().strftime('%Y%m%d%H%M%S')

        input_file = p_body.lineage_source_file or methods.get_previous_state(p_body.user_id, "source_file")

        filename = f"{execution_id}_job_boundaries.json"

        job_dir = methods.get_lineage_upload_dir(p_body.user_id, "jobs")

        os.makedirs(job_dir, exist_ok=True)

        file_path = os.path.join(job_dir, filename)

        source_path = methods.resolve_lineage_artifact(
            p_body.user_id,
            "sources",
            input_file,
            base_type="upload"
        )

        methods.detect_job_boundaries(source_path, file_path)

        methods.save_lineage_state(
            execution_id,
            p_body.user_id,
            {
                "job_boundaries_file": filename,
                "parsed_stage_file": None,
                "dataset_links_file": None,
                "sql_metadata_file": None,
                "normalized_graph_file": None,
                "lineage_graph_file": None,
                "layout_file": None,
                "lineage_options": None
            }
        )

        return {"Job_Boundaries_File": filename}

    except Exception as e:
        return {"error": str(e)}


