@router.post(
    "/read_lineage_sources",
    operation_id="read_lineage_sources",
    summary="Read ETL pseudocode files",
    description="Reads ETL pseudocode files and consolidates them into a lineage source JSON artifact."
)
async def read_lineage_sources(p_body: ReadLineageSources):
    """
    Load pseudocode ETL job files.

    This endpoint reads one or more pseudocode ETL job files and consolidates them
    into a structured lineage source JSON file used by downstream lineage tools.

    The selected filenames also become the canonical lineage scope for this run.
    Later tools should continue to reuse artifacts derived from this same source set.

    LLM usage guidance:
        - Call this immediately after file selection.
        - The chosen files define the lineage scope and later deterministic output naming.
        - Do not skip this step even if the user already named the file in plain text.

    Returns:
        dict:
            Lineage_Source_File (str): Generated lineage source file.
    """

    try:

        execution_id = datetime.now().strftime('%Y%m%d%H%M%S')

        filename = f"{execution_id}_lineage_sources.json"

        source_dir = methods.get_lineage_upload_dir(p_body.user_id, "sources")

        os.makedirs(source_dir, exist_ok=True)

        file_path = os.path.join(source_dir, filename)

        # job_paths = [
        #     os.path.join(source_dir, f)
        #     for f in p_body.job_files
        # ]
        job_paths = []
        for f in p_body.job_files:
            full_path = os.path.join(source_dir, f)
 
            if not os.path.exists(full_path):
                return {"error": f"File not found: {f}"}
 
            job_paths.append(full_path)

        methods.read_etl_sources(job_paths, file_path)

        methods.save_lineage_state(
            execution_id,
            p_body.user_id,
            {
                "source_file": filename,
                "source_files": p_body.job_files,
                "job_boundaries_file": None,
                "parsed_stage_file": None,
                "dataset_links_file": None,
                "sql_metadata_file": None,
                "normalized_graph_file": None,
                "lineage_graph_file": None,
                "layout_file": None,
                "lineage_options": None
            }
        )

        return {"Lineage_Source_File": filename}

    except Exception as e:
        return {"error": str(e)}


