@router.post(
    "/available_lineage_sources",
    operation_id="available_lineage_sources",
    summary="Returns ETL pseudocode files available for lineage generation",
    description="Scans lineage source directory and returns ETL pseudocode files available for lineage analysis."
)
async def available_lineage_sources(p_body: AvailableLineageSources):
    """
    Retrieve ETL pseudocode files available for lineage processing.

    This endpoint scans the lineage source directory associated with the user
    and returns pseudocode files that can be used as input for lineage extraction.

    These files typically contain ETL job pseudocode exported from ETL tools
    such as DataStage or similar systems.

    LLM usage guidance:
        - Call this first whenever file scope is unknown.
        - Use only filenames returned by this tool.
        - If exactly one relevant file is available and the user wants lineage generation, that file can usually be selected directly.

    Args:
        p_body (AvailableLineageSources):
            user_id (str): Unique identifier for the user.

    Returns:
        dict:
            Available_Lineage_Sources (List[str]): List of available ETL pseudocode files.
            error (str, optional): Error message if retrieval fails.
    """

    try:

        log_file = methods.get_or_create_file(
            agent_name="lineage_agent",
            tool_name="available_lineage_sources"
        )
        # log_file = None
        
        execution_id = datetime.now().strftime('%Y-%m-%d-%H-%M-%S')

        lineage_dir = methods.get_lineage_upload_dir(p_body.user_id, "sources")
        os.makedirs(lineage_dir, exist_ok=True)
        files = [
            filename for filename in methods.list_files_in_directory(lineage_dir)
            if os.path.splitext(filename)[1].lower() in SUPPORTED_LINEAGE_SOURCE_EXTENSIONS
        ]

        # dbg.dprint2(script_name, execution_id, "status", "Lineage sources fetched", log_file)

        return {"Available_Lineage_Sources": files}

    except Exception as e:
        tb = traceback.format_exc()
        print(tb)
        return {"error": str(e)}


