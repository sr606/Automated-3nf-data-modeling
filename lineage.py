@router.post(
    "/normalize_lineage_graph",
    operation_id="normalize_lineage_graph",
    summary="Normalize lineage graph",
    description="Convert raw lineage relationships into structured graph nodes."
)
async def normalize_lineage_graph(p_body: NormalizeLineageGraph):
    """
    Normalize lineage graph.

    Converts extracted dataset links and SQL metadata into structured lineage nodes.

    This is the main abstraction step. The provided options tell the backend
    whether to favor a clean logical lineage or a more detailed technical one.
    The LLM should choose these options deliberately based on the user's intent.

    Node categories include:

        SOURCE
        TRANSFORM
        DATASET
        TARGET
        LOOKUP

    Returns:
        dict:
            Normalized_Graph_File (str): JSON file containing normalized graph.
    """

    try:

        execution_id = datetime.now().strftime('%Y%m%d%H%M%S')

        dataset_file = p_body.dataset_links_file or methods.get_previous_state(p_body.user_id, "dataset_links_file")
        sql_file = p_body.sql_metadata_file or methods.get_previous_state(p_body.user_id, "sql_metadata_file")

        filename = f"{execution_id}_normalized_graph.json"

        graph_dir = methods.get_lineage_upload_dir(p_body.user_id, "normalized")

        os.makedirs(graph_dir, exist_ok=True)

        path = os.path.join(graph_dir, filename)

        dataset_path = methods.resolve_lineage_artifact(
            p_body.user_id,
            "datasets",
            dataset_file,
            base_type="upload"
        )
        sql_path = methods.resolve_lineage_artifact(
            p_body.user_id,
            "sql",
            sql_file,
            base_type="upload"
        )

        methods.normalize_lineage_graph(
            dataset_path,
            sql_path,
            path,
            p_body.options.model_dump()
        )

        methods.save_lineage_state(
            execution_id,
            p_body.user_id,
            {
                "normalized_graph_file": filename,
                "lineage_options": p_body.options.model_dump(),
                "lineage_graph_file": None,
                "layout_file": None
            }
        )

        return {"Normalized_Graph_File": filename}

    except Exception as e:
        return {"error": str(e)}


